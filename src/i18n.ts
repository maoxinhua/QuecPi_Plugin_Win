/** Current language pack: zh for any zh-* locale, else en. */
function pick(): Dict {
  const lang = (vscode.env.language || 'en').toLowerCase();
  return lang.startsWith('zh') ? zh : en;
}

export function isChinese(): boolean {
  return (vscode.env.language || 'en').toLowerCase().startsWith('zh');
}

/** Translate one key; falls back to the key itself if missing. */
export function t(key: string): string {
  return pick()[key] ?? en[key] ?? key;
}
